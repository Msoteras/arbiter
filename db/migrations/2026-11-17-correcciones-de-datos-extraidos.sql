-- 2026-11-17 · document_analysis_correction: the document data an analyst corrected.
-- Apply before deploying the code (ddl-auto=validate). Idempotent.
-- Afterwards run the CREATE OR REPLACE FUNCTION arbiter_common.create_tenant_schema block from
-- init-multitenant.sql, so new insurers are created with the table.

BEGIN;

DO $$
DECLARE
    tenant TEXT;
BEGIN
    FOR tenant IN SELECT schema_name FROM arbiter_common.insurer LOOP

        EXECUTE format($ddl$
            CREATE TABLE IF NOT EXISTS %I.document_analysis_correction (
                id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                field               VARCHAR(20)  NOT NULL,
                field_name          VARCHAR(100),
                previous_value      TEXT,
                new_value           TEXT         NOT NULL,
                corrected_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
                analyst_id          BIGINT       NOT NULL REFERENCES %I.claims_analyst(id),
                case_document_id    BIGINT       NOT NULL REFERENCES %I.case_documents(id) ON DELETE CASCADE,

                CONSTRAINT document_analysis_correction_field_valid CHECK (
                    field IN ('DOCUMENT_DATE', 'AMOUNT', 'ITEM_DESCRIPTION', 'ITEM_ATTRIBUTE', 'DETAIL')),
                CONSTRAINT document_analysis_correction_field_name_valid CHECK (
                    (field_name IS NOT NULL) = (field IN ('ITEM_ATTRIBUTE', 'DETAIL')))
            )$ddl$, tenant, tenant, tenant);

        EXECUTE format(
            'CREATE INDEX IF NOT EXISTS idx_document_analysis_correction_document ON %I.document_analysis_correction (case_document_id)',
            tenant);

    END LOOP;
END $$;

COMMIT;
