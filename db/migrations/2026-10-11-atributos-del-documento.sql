-- 2026-10-11 · What a document says identifies the item stops being three fixed columns.
--   · document_analysis.brand / model / imei only fit a cellphone or a laptop. Each document is now
--     read for the names the policy identifies its item by (aseguradora_*.atributo_bien), and what
--     it says is stored one row per datum in the new document_attribute. A line of insurance with
--     other data (a plate, a chassis number) needs no schema change.
--   · The IMEI becomes one more row of atributo_bien ('IMEI'), copied from poliza.imei: it was the
--     last datum of the item read from a column of its own.
--   · What was already read is copied over: brand → 'marca', model → 'modelo', imei → 'IMEI'.
-- The three old columns and poliza.imei are NOT dropped here: the deployed cases-service still
-- selects the former, and dropping them before the deploy breaks the case detail. They go in a
-- later migration, once nothing deployed reads them.
-- Additive, so it can run before the deploy; it MUST have run by then, because the new
-- classification-service validates document_attribute at startup (ddl-auto: validate).
-- Afterwards run the CREATE OR REPLACE FUNCTION arbiter_common.create_tenant_schema block from
-- init-multitenant.sql. Idempotent.

BEGIN;

DO $$
DECLARE
    insurer_schema TEXT;
    tenant         TEXT;
BEGIN
    FOR insurer_schema IN
        SELECT schema_name FROM information_schema.schemata WHERE schema_name LIKE 'aseguradora\_%'
    LOOP
        EXECUTE format($sql$
            INSERT INTO %1$I.atributo_bien (poliza_id, nombre, valor)
            SELECT p.id, 'IMEI', p.imei
              FROM %1$I.poliza p
             WHERE btrim(coalesce(p.imei, '')) <> ''
            ON CONFLICT (poliza_id, nombre) DO NOTHING;
        $sql$, insurer_schema);

        RAISE NOTICE '%: IMEI pasado a atributo_bien', insurer_schema;
    END LOOP;

    FOR tenant IN SELECT schema_name FROM arbiter_common.insurer LOOP
        EXECUTE format($sql$
            CREATE TABLE IF NOT EXISTS %1$I.document_attribute (
                id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name            VARCHAR(60)  NOT NULL,
                value           TEXT         NOT NULL,
                analysis_id     BIGINT       NOT NULL REFERENCES %1$I.document_analysis(id) ON DELETE CASCADE
            );

            INSERT INTO %1$I.document_attribute (name, value, analysis_id)
            SELECT a.name, a.value, da.id
              FROM %1$I.document_analysis da
             CROSS JOIN LATERAL (VALUES
                    ('marca',  da.brand),
                    ('modelo', da.model),
                    ('IMEI',   da.imei)
                   ) AS a (name, value)
             WHERE btrim(coalesce(a.value, '')) <> ''
               AND NOT EXISTS (
                       SELECT 1 FROM %1$I.document_attribute existing
                        WHERE existing.analysis_id = da.id AND existing.name = a.name)
             ORDER BY da.id;
        $sql$, tenant);

        RAISE NOTICE '%: document_attribute creada y cargada', tenant;
    END LOOP;
END $$;

COMMIT;
