-- 2026-10-14 · Document types move from the frontend into the database. Step 1 of 2.
--   · arbiter_common.document_type: the catalog, code + name, the same for every insurer.
--   · <tenant>.branch_document_type: which of them each branch may ask for. Every branch gets the
--     ones its schedule and its Fast Track lists already use, so no insurer loses a document;
--     Celulares and Tecnología Portátil also get the set a new insurer gets: all six documents
--     for Celulares, and Tecnología Portátil without the IMEI deregistration and last connection.
--   · <tenant>.document_requirement gains document_type_id, keyed to the catalog and to the
--     branch's own list. Refuses to run while a schedule row holds a code the catalog doesn't
--     know: load it into document_type first.
-- The free-text document_type stays, kept in step by a trigger, so the code already deployed
-- (which writes only the code) and the new one (which writes only the id) share the database.
-- Step 2, 2026-10-14-tipos-de-documento-paso-2.sql, drops it once the new code is deployed.
-- Idempotent.

BEGIN;

CREATE TABLE IF NOT EXISTS arbiter_common.document_type (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    VARCHAR(50)  NOT NULL UNIQUE,
    name    VARCHAR(100) NOT NULL
);

INSERT INTO arbiter_common.document_type (code, name) VALUES
    ('police_report',       'Denuncia policial'),
    ('purchase_proof',      'Comprobante de compra'),
    ('imei_deregistration', 'Baja de IMEI (ENACOM)'),
    ('last_connection',     'Captura de última conexión'),
    ('repair_quote',        'Presupuesto de reparación'),
    ('item_photo',          'Foto del bien')
ON CONFLICT (code) DO NOTHING;

-- Fills whichever of the two columns the writer left out. NOT NULL is checked after BEFORE
-- triggers, so both columns keep it.
CREATE OR REPLACE FUNCTION arbiter_common.sync_document_requirement_type() RETURNS trigger AS $fn$
BEGIN
    IF NEW.document_type_id IS NULL AND NEW.document_type IS NOT NULL THEN
        SELECT id INTO NEW.document_type_id
          FROM arbiter_common.document_type WHERE code = NEW.document_type;
    ELSIF NEW.document_type IS NULL AND NEW.document_type_id IS NOT NULL THEN
        SELECT code INTO NEW.document_type
          FROM arbiter_common.document_type WHERE id = NEW.document_type_id;
    END IF;
    RETURN NEW;
END;
$fn$ LANGUAGE plpgsql;

DO $$
DECLARE
    tenant  TEXT;
    unknown TEXT;
BEGIN
    FOR tenant IN SELECT schema_name FROM arbiter_common.insurer LOOP
        EXECUTE format($sql$
            CREATE TABLE IF NOT EXISTS %1$I.branch_document_type (
                id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                branch_id           BIGINT NOT NULL REFERENCES %1$I.branch(id) ON DELETE CASCADE,
                document_type_id    BIGINT NOT NULL REFERENCES arbiter_common.document_type(id),

                CONSTRAINT branch_document_type_unique UNIQUE (branch_id, document_type_id)
            )
        $sql$, tenant);

        IF EXISTS (
                SELECT 1 FROM information_schema.columns
                 WHERE table_schema = tenant AND table_name = 'document_requirement'
                   AND column_name = 'document_type_id') THEN
            RAISE NOTICE '%: la agenda ya apunta al catálogo', tenant;
            CONTINUE;
        END IF;

        EXECUTE format($sql$
            SELECT string_agg(DISTINCT r.document_type, ', ')
              FROM %1$I.document_requirement r
             WHERE NOT EXISTS (SELECT 1 FROM arbiter_common.document_type dt
                                WHERE dt.code = r.document_type)
        $sql$, tenant) INTO unknown;

        IF unknown IS NOT NULL THEN
            RAISE EXCEPTION '%: la agenda usa tipos que no están en el catálogo: %', tenant, unknown;
        END IF;

        -- What each branch already asks for: its schedule, plus its coverages' Fast Track lists.
        EXECUTE format($sql$
            INSERT INTO %1$I.branch_document_type (branch_id, document_type_id)
            SELECT used.branch_id, dt.id
              FROM (
                    SELECT branch_id, document_type AS code FROM %1$I.document_requirement
                    UNION
                    SELECT r.branch_id, jsonb_array_elements_text(r.configuration::jsonb -> 'requiredDocumentTypes')
                      FROM %1$I.insurer_rule r
                     WHERE r.rule_type = 'FAST_TRACK' AND r.branch_id IS NOT NULL
                       AND jsonb_typeof(r.configuration::jsonb -> 'requiredDocumentTypes') = 'array'
                   ) AS used
              JOIN arbiter_common.document_type dt ON dt.code = used.code
            ON CONFLICT (branch_id, document_type_id) DO NOTHING
        $sql$, tenant);

        -- The platform's two branches get what a new insurer gets.
        EXECUTE format($sql$
            INSERT INTO %1$I.branch_document_type (branch_id, document_type_id)
            SELECT b.id, dt.id
              FROM %1$I.branch b
              JOIN arbiter_common.document_type dt
                ON b.external_name = 'Celulares'
                OR (b.external_name = 'Tecnología Portátil'
                    AND dt.code IN ('police_report', 'purchase_proof', 'repair_quote', 'item_photo'))
            ON CONFLICT (branch_id, document_type_id) DO NOTHING
        $sql$, tenant);

        EXECUTE format($sql$
            ALTER TABLE %1$I.document_requirement ADD COLUMN document_type_id BIGINT;

            UPDATE %1$I.document_requirement r
               SET document_type_id = dt.id
              FROM arbiter_common.document_type dt
             WHERE dt.code = r.document_type;

            CREATE TRIGGER document_requirement_sync_type
                BEFORE INSERT OR UPDATE ON %1$I.document_requirement
                FOR EACH ROW EXECUTE FUNCTION arbiter_common.sync_document_requirement_type();

            ALTER TABLE %1$I.document_requirement
                ALTER COLUMN document_type_id SET NOT NULL,
                ADD CONSTRAINT document_requirement_document_type_id_fkey
                    FOREIGN KEY (document_type_id) REFERENCES arbiter_common.document_type(id),
                ADD CONSTRAINT document_requirement_branch_document_type_fk
                    FOREIGN KEY (branch_id, document_type_id)
                    REFERENCES %1$I.branch_document_type (branch_id, document_type_id);
        $sql$, tenant);

        RAISE NOTICE '%: agenda migrada al catálogo', tenant;
    END LOOP;
END $$;

COMMIT;
