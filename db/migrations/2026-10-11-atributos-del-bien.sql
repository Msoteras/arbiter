-- 2026-10-11 · The insurer database states what identifies each insured item as name/value rows
-- (aseguradora_*.atributo_bien: 'marca' → 'Samsung', 'modelo' → 'Galaxy A56').
--   · Until now the only description was poliza.bien_asegurado, free text, and the fraud score
--     looked for the make and model of each document inside it. "Galaxy A56 5G" was not found in
--     "Samsung Galaxy A56", and "Apple" is nowhere in "iPhone 15 Pro": both scored as document
--     inconsistencies.
--   · Rows and not columns because each line of insurance identifies its items differently.
--   · Existing policies get marca and modelo derived from bien_asegurado: the first word is the
--     make, except Apple's products, which the text names without it. Policies with no
--     bien_asegurado get no rows, and nothing is compared for them.
-- Additive: the deployed code doesn't read the table, so this can run before the deploy. Once
-- classification-service reads it, a missing table fails every classification. Idempotent.

BEGIN;

DO $$
DECLARE
    insurer_schema TEXT;
BEGIN
    FOR insurer_schema IN
        SELECT schema_name FROM information_schema.schemata WHERE schema_name LIKE 'aseguradora\_%'
    LOOP
        EXECUTE format($sql$
            CREATE TABLE IF NOT EXISTS %1$I.atributo_bien (
                id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                poliza_id       BIGINT        NOT NULL REFERENCES %1$I.poliza(id) ON DELETE CASCADE,
                nombre          VARCHAR(60)   NOT NULL,
                valor           VARCHAR(255)  NOT NULL,

                CONSTRAINT atributo_bien_poliza_nombre_unique UNIQUE (poliza_id, nombre)
            );

            INSERT INTO %1$I.atributo_bien (poliza_id, nombre, valor)
            SELECT p.id, a.nombre, a.valor
              FROM %1$I.poliza p
             CROSS JOIN LATERAL (
                    SELECT p.bien_asegurado ~* '^(iphone|ipad|macbook)' AS es_apple
                   ) marca
             CROSS JOIN LATERAL (VALUES
                    ('marca',  CASE WHEN marca.es_apple THEN 'Apple'
                                    ELSE split_part(p.bien_asegurado, ' ', 1) END),
                    ('modelo', CASE WHEN marca.es_apple THEN p.bien_asegurado
                                    ELSE btrim(substr(p.bien_asegurado,
                                                      length(split_part(p.bien_asegurado, ' ', 1)) + 1)) END)
                   ) AS a (nombre, valor)
             WHERE btrim(coalesce(p.bien_asegurado, '')) <> ''
               AND a.valor <> ''
            ON CONFLICT (poliza_id, nombre) DO NOTHING;
        $sql$, insurer_schema);

        RAISE NOTICE '%: atributos del bien cargados', insurer_schema;
    END LOOP;
END $$;

COMMIT;
