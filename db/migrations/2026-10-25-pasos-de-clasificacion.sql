-- 2026-10-25 · classification_step: lo que está haciendo cada clasificación, para el tablero del motor.
-- Aplicar antes de desplegar el código (ddl-auto=validate). Idempotente.

BEGIN;

DO $$
DECLARE
    tenant TEXT;
BEGIN
    FOR tenant IN SELECT schema_name FROM arbiter_common.insurer LOOP

        EXECUTE format($ddl$
            CREATE TABLE IF NOT EXISTS %I.classification_step (
                id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                case_id         BIGINT       NOT NULL REFERENCES %I.cases(id) ON DELETE CASCADE,
                stage           VARCHAR(30)  NOT NULL,
                detail          VARCHAR(50),
                item_index      INTEGER,
                item_count      INTEGER,
                result          VARCHAR(50),
                occurred_at     TIMESTAMPTZ  NOT NULL
            )$ddl$, tenant, tenant);

        EXECUTE format(
            'CREATE INDEX IF NOT EXISTS idx_classification_step_case ON %I.classification_step (case_id, occurred_at)',
            tenant);
        EXECUTE format(
            'CREATE INDEX IF NOT EXISTS idx_classification_step_occurred ON %I.classification_step (occurred_at)',
            tenant);

    END LOOP;
END $$;

COMMIT;
